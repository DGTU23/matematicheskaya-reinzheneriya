#!/bin/bash
# =============================================================================
# Сценарий нагрузочного тестирования TCP-сервера
# Методика «Математическая реинженерия ИТ-систем», ДГТУ
# =============================================================================
#
# Использование:
#   bash нагрузочный_тест.sh [хост] [порт]
#
# Примеры:
#   bash нагрузочный_тест.sh 127.0.0.1 8080
#   bash нагрузочный_тест.sh 192.168.1.100 9090
#
# Требования:
#   - tcpkali: установить через  sudo apt install tcpkali
#              или собрать из исходников: https://github.com/siriusdb/tcpkali
#   - Запущенный TCP-сервер на указанном хосте и порту
# =============================================================================

HOST="${1:-127.0.0.1}"
PORT="${2:-8080}"
RESULTS_DIR="./результаты_$(date +%Y%m%d_%H%M%S)"

echo "=================================================="
echo "  Нагрузочный тест TCP-сервера"
echo "  Цель: ${HOST}:${PORT}"
echo "  Результаты будут сохранены в: ${RESULTS_DIR}"
echo "=================================================="
echo ""

# Проверяем наличие tcpkali
if ! command -v tcpkali &> /dev/null; then
    echo "ОШИБКА: tcpkali не найден."
    echo "Установите: sudo apt-get install tcpkali"
    echo ""
    echo "Альтернатива — использовать wrk или ab:"
    echo "  wrk -t4 -c100 -d30s http://${HOST}:${PORT}"
    exit 1
fi

mkdir -p "${RESULTS_DIR}"

# =============================================================================
# Сценарий 1: Малая нагрузка (10 клиентов, 15 секунд)
# =============================================================================
echo "[1/3] Малая нагрузка: 10 клиентов, 15 сек..."
tcpkali \
    --connections 10 \
    --duration 15s \
    --message "$(python3 -c 'print("A"*256)')" \
    --latency-percentiles 50,95,99 \
    "${HOST}:${PORT}" \
    2>&1 | tee "${RESULTS_DIR}/сценарий_1_малая_нагрузка.txt"
echo ""

# =============================================================================
# Сценарий 2: Средняя нагрузка (50 клиентов, 30 секунд)
# =============================================================================
echo "[2/3] Средняя нагрузка: 50 клиентов, 30 сек..."
tcpkali \
    --connections 50 \
    --duration 30s \
    --message "$(python3 -c 'print("A"*256)')" \
    --latency-percentiles 50,95,99 \
    "${HOST}:${PORT}" \
    2>&1 | tee "${RESULTS_DIR}/сценарий_2_средняя_нагрузка.txt"
echo ""

# =============================================================================
# Сценарий 3: Высокая нагрузка (100 клиентов, 30 секунд)
# =============================================================================
echo "[3/3] Высокая нагрузка: 100 клиентов, 30 сек..."
tcpkali \
    --connections 100 \
    --duration 30s \
    --message "$(python3 -c 'print("A"*256)')" \
    --latency-percentiles 50,95,99 \
    "${HOST}:${PORT}" \
    2>&1 | tee "${RESULTS_DIR}/сценарий_3_высокая_нагрузка.txt"
echo ""

# =============================================================================
# Итоговая сводка
# =============================================================================
echo "=================================================="
echo "  Тест завершён. Результаты сохранены в:"
echo "  ${RESULTS_DIR}/"
echo ""
echo "  Что делать дальше:"
echo "  1. Скопируйте числа из файлов в Протокол эксперимента"
echo "  2. Обратите внимание на 95-й и 99-й процентили задержки"
echo "  3. Запишите загрузку CPU во время теста (команда: top или htop)"
echo "=================================================="
